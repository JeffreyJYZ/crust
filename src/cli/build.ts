/** LSMinimumSystemVersion when the config does not name one. */
const DEFAULT_MINIMUM_SYSTEM_VERSION = "13.0";

/**
 * Extensions embedded as text. Everything else is embedded as bytes, because a
 * text import of a PNG or a `.woff2` would arrive corrupted rather than fail.
 * The list matches the bridge's own `CONTENT_TYPES` text half, so what is
 * embedded as text is exactly what is served with a text content type.
 */
const TEXT_ASSET_EXTENSIONS = new Set([
	".html",
	".htm",
	".js",
	".mjs",
	".cjs",
	".css",
	".json",
	".map",
	".txt",
	".svg",
	".webmanifest",
	".xml",
]);

export interface AssetFile {
	/** Request path, always `/`-prefixed and `/`-separated. */
	path: string;
	bytes: Uint8Array;
	text: boolean;
}

/**
 * Walk the asset directory and return every file as a request path plus its bytes.
 *
 * A compiled binary has no project directory on the recipient's machine, so the
 * whole tree has to travel inside it. One file (`index.html`) was the v1
 * shortcut and it is the reason a real frontend could not ship; walking the
 * directory removes that limit without a bundler. Which directory is
 * `build.assets`' business — `public/` by default, a Vite `dist/web` for a
 * project that builds its frontend.
 */
async function collectAssets(assetsDir: string): Promise<AssetFile[]> {
	if (!(await exists(assetsDir, "dir"))) return [];
	const files: AssetFile[] = [];

	async function walk(dir: string, prefix: string): Promise<void> {
		const entries = await readdir(dir, { withFileTypes: true });
		entries.sort((left, right) => left.name.localeCompare(right.name));
		for (const entry of entries) {
			if (entry.name === ".DS_Store") continue;
			const full = join(dir, entry.name);
			const url = `${prefix}/${entry.name}`;
			if (entry.isDirectory()) {
				await walk(full, url);
				continue;
			}
			if (!entry.isFile()) continue;
			const bytes = new Uint8Array(await readFile(full));
			const dot = entry.name.lastIndexOf(".");
			const extension = dot === -1 ? "" : entry.name.slice(dot).toLowerCase();
			files.push({ path: url, bytes, text: TEXT_ASSET_EXTENSIONS.has(extension) });
		}
	}

	await walk(assetsDir, "");
	return files;
}

/**
 * The generated asset module.
 *
 * Text stays a string so `runtime.ts` can hand `index.html` to the bridge as the
 * document and every JS/CSS file is served with no decode step. Binary files
 * are base64 and decoded at import time, which is the one encoding that survives
 * `bun build --compile` unchanged.
 */
export function assetsModuleSource(files: readonly AssetFile[]): string {
	const lines = [
		"// Generated by `crust build`. Edit nothing here.",
		"// The whole asset tree, embedded so a compiled binary needs no project directory.",
		"const decode = (data: string): Uint8Array =>",
		"\tUint8Array.from(atob(data), (char) => char.charCodeAt(0));",
		"",
		"export const assets: Record<string, string | Uint8Array> = {",
	];
	for (const file of files) {
		const key = JSON.stringify(file.path);
		if (file.text) {
			lines.push(`\t${key}: ${JSON.stringify(Buffer.from(file.bytes).toString("utf8"))},`);
		} else {
			lines.push(
				`\t${key}: decode(${JSON.stringify(Buffer.from(file.bytes).toString("base64"))}),`,
			);
		}
	}
	lines.push("};", "");
	return lines.join("\n");
}

/**
 * The generated entry a compiled crust app runs.
 *
 * The app's config and `main.ts` are imported statically so `bun build
 * --compile` bundles both; `startApp` then starts the bridge and platform and
 * the wrapper's own literal `import("<main.ts>")` runs the app. The generated
 * `crust-assets.ts` carries every file under the configured asset directory
 * (`build.assets`, `public/` by default), so the bridge inside the binary serves
 * the whole frontend — separate JS, CSS, fonts and images included — with no
 * project directory on disk.
 *
 * `config.dev` is dropped from the generated entry, and only there: `dev.url`
 * names a dev server, a built app has none, and keeping it would point the
 * window at a port nobody is listening on instead of the embedded document.
 * The project's own `crust.config.ts` is untouched, so `crust dev` still uses it.
 */
function wrapperSource(options: {
	configPath: string;
	entryPath: string;
	assetsPath: string;
	runtimePath: string;
}): string {
	const body = [
		"// Generated by `crust build`. Edit nothing here.",
		`import config from ${JSON.stringify(options.configPath)};`,
		`import { assets } from ${JSON.stringify(options.assetsPath)};`,
		`import { startApp } from ${JSON.stringify(options.runtimePath)};`,
		"// A built app has no dev server: drop dev.url so the window loads the",
		"// embedded document instead of a port nobody is listening on.",
		"const production = { ...config, dev: undefined };",
		"await startApp({",
		"\tconfig: production,",
		"\tassets,",
		`\tentryModule: () => import(${JSON.stringify(options.entryPath)}),`,
		"});",
	];
	return `${body.join("\n")}\n`;
}

/**
 * What `build.assets` resolved to: the files to embed, or the sentence that
 * stops the build. A failed `beforeBuildCommand` and an empty frontend
 * directory are both failures here, never a package made from stale bytes.
 */
export type ResolvedAssets =
	{ ok: true; files: AssetFile[]; label: string } | { ok: false; failure: string };

/** The `run its build` half shared by the two "nothing to embed" failures. */
const FRONTEND_HINT = "run its build (for Vite, `bun --bun x vite build`) then `crust build`";

/**
 * Run `build.beforeBuildCommand` (if any), then read `build.assets`.
 *
 * The command runs first and its non-zero exit aborts: a framework app must
 * never ship whatever happened to be in its asset directory from an earlier
 * run. Stdio is inherited (`runShell`), so the frontend's own output is the
 * user's to read. Only after it returns is the directory read — and checked
 * again, because "exited 0" is not the same fact as "produced an index.html".
 *
 * Returns rather than throws so `build` prints one line in its own format.
 */
export async function resolveAssets(
	dir: string,
	config: CrustConfig,
	outDir: string,
): Promise<ResolvedAssets> {
	const command = config.build?.beforeBuildCommand;
	if (command) {
		line("before", command);
		const code = await runShell(command, dir);
		if (code !== 0) {
			return {
				ok: false,
				failure:
					`build.beforeBuildCommand \`${command}\` exited with ${code} — ` +
					"the frontend build failed, so nothing was packaged",
			};
		}
	}
	const built = command !== undefined;

	const setting = config.build?.assets;
	const assetsDir = resolve(dir, setting ?? "public");
	const label = setting ?? "public";

	// Only a *named* directory is a promise crust can hold you to. Absent, the
	// old behaviour stands: `public/` is embedded if it exists, and a project
	// with no frontend directory still builds.
	if (setting) {
		// `dist` is also where this command writes, so a second build would walk
		// its own binary and embed it. Refuse before that can happen.
		if (assetsDir === outDir) {
			return {
				ok: false,
				failure:
					`build.assets "${setting}" is ${outDir}, where crust build writes its own ` +
					"output — point it at the frontend's directory (for Vite, dist/web) so a " +
					"second build cannot embed its own binary",
			};
		}
		if (!(await exists(assetsDir, "dir"))) {
			return {
				ok: false,
				failure:
					`build.assets "${setting}" is not a directory (resolved to ${assetsDir}) — ` +
					(built
						? "the frontend build produced nothing there, so nothing was packaged"
						: `the frontend has not been built yet; ${FRONTEND_HINT}`),
			};
		}
		if (!(await exists(join(assetsDir, "index.html")))) {
			return {
				ok: false,
				failure:
					`build.assets "${setting}" holds no index.html (looked in ${assetsDir}) — ` +
					(built
						? "the frontend build produced nothing there, so nothing was packaged"
						: `the frontend has not been built yet; ${FRONTEND_HINT}`),
			};
		}
	}

	return { ok: true, files: await collectAssets(assetsDir), label };
}

/**
 * `crust build` — compile the backend with Bun, assemble `X.app`, then ad-hoc
 * sign it. A Developer ID signature is `crust sign`'s job, not this one's.
 *
 * The two sizes are printed separately because they answer different questions:
 * the compiled binary is what Bun produced, the assembled bundle is what a
 * recipient's disk gives up.
 */
export /**
 * The crust package the project itself depends on, when it has one.
 *
 * The generated wrapper has to import the runtime through the same module the app's
 * `import "crust"` resolves to. Otherwise a built binary carries two copies of the
 * framework — the wrapper's and the project's — and each has its own `app` singleton,
 * so `app.run()` inside the entry never sees the config the wrapper passed and falls
 * back to loading one from the working directory, which a launched app does not have.
 * That is exactly how a scaffold installed from git failed while the same scaffold
 * linked to a checkout worked: the symlink made both specifiers one realpath.
 */
async function projectCrustRoot(dir: string): Promise<string> {
	const candidate = join(dir, "node_modules", "crust");
	try {
		const manifest = (await Bun.file(join(candidate, "package.json")).json()) as {
			name?: unknown;
		};
		if (manifest.name === "crust" && (await exists(join(candidate, "src", "runtime.ts"))))
			return await realpath(candidate);
	} catch {
		// No usable dependency: fall back to the framework this CLI carries.
	}
	return await frameworkRoot();
}

export async function build(options: CliOptions): Promise<number> {
	const detected = await detectSingle(options);
	if (detected.kind === "error") return fail("build", detected.message);
	if (detected.kind === "app") return buildSingle(detected.app);

	const loaded = await loadConfig({ dir: options.dir, configPath: options.config });
	console.log(`crust build — ${loaded.path}`);
	const config = loaded.config;

	// A missing install is the state a clone or a clean leaves behind, and it has to be
	// said plainly: otherwise the frontend command resolves its tool from a global cache
	// and fails deep inside its own bundler, which reads as crust's fault.
	const needsInstall = await missingInstall(options.dir);
	if (needsInstall) return fail("build", needsInstall);

	const backend = await resolveBackendEntry(options.dir, options.entry);
	if (!backend) {
		return fail(
			"build",
			options.entry
				? `backend entry ${options.entry} does not exist under ${options.dir}`
				: `no backend entry in ${options.dir} — expected src/main.ts or main.ts`,
		);
	}
	const entry = backend.path;

	let iconPath: string | undefined;
	if (config.app.icon) {
		iconPath = resolve(options.dir, config.app.icon);
		if (!(await exists(iconPath))) {
			return fail(
				"build",
				`app.icon ${config.app.icon} does not exist (resolved to ${iconPath})`,
			);
		}
	}

	const minimumSystemVersion =
		config.build?.minimumSystemVersion ?? DEFAULT_MINIMUM_SYSTEM_VERSION;

	const outDir = resolve(options.dir, "dist");
	// beforeBuildCommand runs inside here, before the directory is read: a
	// failed frontend build stops the command rather than packaging stale bytes.
	const resolved = await resolveAssets(options.dir, config, outDir);
	if (!resolved.ok) return fail("build", resolved.failure);
	const assetsLabel = resolved.label;

	await mkdir(outDir, { recursive: true });

	const assets = resolved.files;
	const assetsPath = resolve(outDir, "crust-assets.ts");
	await writeFile(assetsPath, assetsModuleSource(assets), "utf8");
	line(
		"assets",
		assets.length > 0
			? `${assets.length} file${assets.length === 1 ? "" : "s"} from ${assetsLabel}/`
			: `none — ${assetsLabel}/ is empty or missing`,
	);

	const wrapperPath = resolve(outDir, "crust-entry.ts");
	await writeFile(
		wrapperPath,
		wrapperSource({
			configPath: resolve(options.dir, loaded.path),
			entryPath: entry,
			assetsPath,
			runtimePath: resolve(await projectCrustRoot(options.dir), "src/runtime.ts"),
		}),
		"utf8",
	);

	const result = await buildApp({
		entry: wrapperPath,
		binaryName: "crust-app",
		outDir,
		app: {
			id: config.app.id,
			name: config.app.name,
			version: config.app.version,
			iconPath,
			minimumSystemVersion,
		},
	});

	await signApp({ appPath: result.appPath, mode: "adhoc" });

	line("binary", `${formatBytes(result.binaryBytes)}  ${result.binaryPath}`);
	line("app", `${formatBytes(result.assembledBytes)}  ${result.appPath}`);
	line("sign", "ad-hoc (codesign --sign -)");
	line("gatekeeper", "refused on another machine until a Developer ID signature exists");
	console.log(`\ndone — open it locally with: open ${result.appPath}`);
	return 0;
}

/**
 * Never a directory, on any machine. A single-file build has no project tree on
 * the recipient's disk, so the bridge must answer every request from the
 * embedded table rather than from `cwd/public` — which is what `startApp`
 * would fall back to with no `root`.
 */
const NO_PROJECT_ROOT = "/crust-single/no-project";

/**
 * The generated entry a single-file `.app` runs.
 *
 * The config is a literal, not an import: no `crust.config.ts` exists for a
 * single file, and a build must not need one. The page is already bundled
 * JavaScript inside `crust-assets.ts`, so this wrapper carries only the
 * backend and the framework's two commands.
 */
function singleWrapperSource(app: SingleApp, assetsPath: string, root: string): string {
	return [
		"// Generated by `crust build` from a single file. Edit nothing here.",
		`import { app } from ${JSON.stringify(resolve(root, "src/index.ts"))};`,
		`import { assets } from ${JSON.stringify(assetsPath)};`,
		`import { startApp } from ${JSON.stringify(resolve(root, "src/runtime.ts"))};`,
		`import { registerSingleCommands } from ${JSON.stringify(resolve(root, "src/single.ts"))};`,
		"",
		`registerSingleCommands(app, ${JSON.stringify({ file: app.file, name: app.name })});`,
		'app.on("window-all-closed", () => { app.quit(); });',
		"await startApp({",
		`\tconfig: ${JSON.stringify(app.config, null, "\t")},`,
		"\tassets,",
		`\troot: ${JSON.stringify(NO_PROJECT_ROOT)},`,
		"\tentryModule: async () => {",
		"\t\tawait app.run();",
		"\t},",
		"});",
		"",
	].join("\n");
}

/**
 * `crust build app.tsx` — the same page bundle `crust dev` serves, embedded in
 * an `.app` instead of served from disk. No icon, no `beforeBuildCommand` and
 * no `app.icon` exist to read, because a single file has no config to name them.
 */
async function buildSingle(app: SingleApp): Promise<number> {
	console.log(`crust build — ${app.file} (one file, no config)`);

	let page: PageBuild;
	try {
		page = await buildPage(app, { dev: false });
	} catch (error) {
		return fail("build", error instanceof Error ? error.message : String(error));
	}
	line("page", `${join(page.dir, "index.html")} + ${page.entry}`);

	const outDir = resolve(app.dir, "dist");
	await mkdir(outDir, { recursive: true });

	const assets = await collectAssets(page.dir);
	const assetsPath = resolve(outDir, "crust-assets.ts");
	await writeFile(assetsPath, assetsModuleSource(assets), "utf8");
	line(
		"assets",
		`${assets.length} file${assets.length === 1 ? "" : "s"} embedded from the single-file bundle`,
	);

	const wrapperPath = resolve(outDir, "crust-entry.ts");
	await writeFile(
		wrapperPath,
		singleWrapperSource(app, assetsPath, await frameworkRoot()),
		"utf8",
	);

	const result = await buildApp({
		entry: wrapperPath,
		binaryName: "crust-app",
		outDir,
		app: {
			id: app.config.app.id,
			name: app.config.app.name,
			version: app.config.app.version,
			minimumSystemVersion: DEFAULT_MINIMUM_SYSTEM_VERSION,
		},
	});

	await signApp({ appPath: result.appPath, mode: "adhoc" });

	line("binary", `${formatBytes(result.binaryBytes)}  ${result.binaryPath}`);
	line("app", `${formatBytes(result.assembledBytes)}  ${result.appPath}`);
	line("sign", "ad-hoc (codesign --sign -)");
	line("gatekeeper", "refused on another machine until a Developer ID signature exists");
	console.log(`\ndone — open it locally with: open ${result.appPath}`);
	return 0;
}

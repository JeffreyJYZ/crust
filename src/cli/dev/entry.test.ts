/**
 * The generated dev entry: a project with no extensions must spawn the plain runtime untouched, and
 * one with files must import each, register them into the registry `startApp` serves, and parse.
 */

import { describe, expect, test } from "bun:test";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { wrapperSource } from "../build/wrapper.ts";
import { devEntrySource, type DevEntryOptions } from "./entry.ts";

const transpiler = new Bun.Transpiler({ loader: "ts" });
const definePath = fileURLToPath(new URL("../../extensions/define.ts", import.meta.url));
const registryPath = fileURLToPath(new URL("../../extensions/registry.ts", import.meta.url));

const base: DevEntryOptions = {
	configPath: "/p/crust.config.ts",
	entryPath: "/p/src/main.ts",
	runtimePath: "/crust/src/runtime.ts",
	extensionsPath: "/crust/src/extensions/registry.ts",
	projectDir: "/p",
	extensionFiles: [],
};

describe("devEntrySource", () => {
	test("no extensions is empty, so dev spawns src/runtime.ts as before", () => {
		expect(devEntrySource(base)).toBe("");
	});

	test("one extension is imported, registered, and handed to startApp", () => {
		const source = devEntrySource({ ...base, extensionFiles: ["extensions/clock.ts"] });

		expect(source).toContain("async function extensionPlugins() {");
		expect(source).toContain(
			`\tconst extension0 = (await import(${JSON.stringify("/p/extensions/clock.ts")})).default;`,
		);
		expect(source).toContain("\treturn [extension0];");
		expect(source).toContain(
			`import { extensionRegistry } from ${JSON.stringify("/crust/src/extensions/registry.ts")};`,
		);
		expect(source).toContain("const registry = extensionRegistry();");
		expect(source).toContain("registry.register(...(await extensionPlugins()));");
		expect(source).toContain(`\tconfigPath: ${JSON.stringify("/p/crust.config.ts")},`);
		expect(source).toContain("\tregistry,");
		expect(() => transpiler.transformSync(source)).not.toThrow();
	});

	test("two extensions register both, before startApp runs", () => {
		const files = ["extensions/clock.ts", "extensions/ping.ts"];
		const source = devEntrySource({ ...base, extensionFiles: files });
		const lines = source.split("\n");

		expect(lines.slice(0, 4)).toEqual([
			"// Generated by `crust dev`. Edit nothing here.",
			"async function extensionPlugins() {",
			`\tconst extension0 = (await import(${JSON.stringify("/p/extensions/clock.ts")})).default;`,
			`\tconst extension1 = (await import(${JSON.stringify("/p/extensions/ping.ts")})).default;`,
		]);
		expect(source).toContain("\treturn [extension0, extension1];");
		expect(source).toContain("registry.register(...(await extensionPlugins()));");

		const registerAt = lines.indexOf("registry.register(...(await extensionPlugins()));");
		const startAt = lines.indexOf("await startApp({");
		expect(registerAt).toBeGreaterThan(0);
		expect(registerAt).toBeLessThan(startAt);
		expect(() => transpiler.transformSync(source)).not.toThrow();
	});

	test("the registry line is the build wrapper's, for the same file list", () => {
		const files = ["extensions/clock.ts", "extensions/ping.ts"];
		const build = wrapperSource({
			configPath: "/p/crust.config.ts",
			entryPath: "/p/src/main.ts",
			assetsPath: "/p/dist/crust-assets.ts",
			runtimePath: "/crust/src/runtime.ts",
			extensionsPath: "/crust/src/extensions/registry.ts",
			projectDir: "/p",
			extensionFiles: files,
		});
		const dev = devEntrySource({ ...base, extensionFiles: files });

		const registerLine = (source: string): string | undefined =>
			source.split("\n").find((row) => row.startsWith("registry.register("));
		// The extension-loader lines by the shape `extensionEntrySource` generates, not by a path
		// substring: the registry module lives under `extensions/` too, so a dynamic import of it
		// would otherwise count as a loader, and an absolute extension path outside `extensions/`
		// would not count at all. The count assertion below keeps the comparison from going vacuous.
		const loaderLines = (source: string): string[] =>
			source
				.split("\n")
				.filter((row) => /^\tconst extension\d+ = \(await import\(/.test(row));

		expect(registerLine(dev)).toBe("registry.register(...(await extensionPlugins()));");
		expect(registerLine(dev)).toBe(registerLine(build));
		expect(loaderLines(dev)).toEqual(loaderLines(build));
		expect(loaderLines(dev)).toHaveLength(2);
	});

	/**
	 * The whole dev wiring, executed: the generated entry imports a real extension through the real
	 * registry and hands `startApp` a registry that already holds it. Only `startApp` is a stub — it
	 * records what it was given instead of building AppKit.
	 */
	test("the generated entry really fills the registry startApp receives", async () => {
		const dir = await mkdtemp(join(tmpdir(), "crust-dev-entry-"));
		try {
			await writeFile(
				join(dir, "clock.ts"),
				[
					`import { defineExtension } from ${JSON.stringify(definePath)};`,
					'export default defineExtension({ name: "clock", commands: { now: () => "now" } });',
					"",
				].join("\n"),
				"utf8",
			);
			await writeFile(join(dir, "main.ts"), "export const started = true;\n", "utf8");
			await writeFile(
				join(dir, "runtime-stub.ts"),
				[
					"export async function startApp(options: unknown) {",
					"\t(globalThis as Record<string, unknown>).__crustDevStart = options;",
					"}",
					"",
				].join("\n"),
				"utf8",
			);

			const entryPath = join(dir, "dev-entry.ts");
			await writeFile(
				entryPath,
				devEntrySource({
					configPath: join(dir, "crust.config.ts"),
					entryPath: join(dir, "main.ts"),
					runtimePath: join(dir, "runtime-stub.ts"),
					extensionsPath: registryPath,
					projectDir: dir,
					extensionFiles: [join(dir, "clock.ts")],
				}),
				"utf8",
			);
			await import(pathToFileURL(entryPath).href);

			const started = (globalThis as Record<string, unknown>).__crustDevStart as {
				registry: { names(): string[] };
				entryModule: () => Promise<unknown>;
			};
			expect(started.registry.names()).toEqual(["clock"]);
			expect(typeof started.entryModule).toBe("function");
		} finally {
			await rm(dir, { recursive: true, force: true });
			delete (globalThis as Record<string, unknown>).__crustDevStart;
		}
	});
});

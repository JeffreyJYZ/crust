/**
 * The generated entry `crust dev` spawns when the project has extensions. With none it returns ""
 * and dev spawns `src/runtime.ts --config … --entry …` exactly as before, so a project without
 * extensions has a byte-identical dev path.
 * The import block comes from the same `extensionEntrySource`/`renderExtensionImports` pair
 * `crust build` writes into its wrapper, and the registry they fill is handed to `startApp`, which
 * is the registry the bridge serves — so `crust dev` and a built app register the same extensions.
 */

import { extensionEntrySource, renderExtensionImports } from "@/extensions/entry-source.ts";

export interface DevEntryOptions {
	configPath: string;
	entryPath: string;
	/** The framework's `src/runtime.ts`, so both paths call the same `startApp`. */
	runtimePath: string;
	/** Module exporting `extensionRegistry`; the one a built wrapper imports. */
	extensionsPath: string;
	projectDir: string;
	/** Files that loaded; empty is the "spawn the plain runtime" signal. */
	extensionFiles: readonly string[];
}

export function devEntrySource(options: DevEntryOptions): string {
	const files = options.extensionFiles;
	if (files.length === 0) return "";

	const imports = extensionEntrySource({
		files,
		projectDir: options.projectDir,
		header: false,
	});

	return [
		"// Generated by `crust dev`. Edit nothing here.",
		imports.trimEnd(),
		`import { startApp } from ${JSON.stringify(options.runtimePath)};`,
		`import { extensionRegistry } from ${JSON.stringify(options.extensionsPath)};`,
		"",
		"const registry = extensionRegistry();",
		renderExtensionImports(files),
		"await startApp({",
		`\tconfigPath: ${JSON.stringify(options.configPath)},`,
		`\tentryModule: () => import(${JSON.stringify(options.entryPath)}),`,
		"\tregistry,",
		"});",
		"",
	].join("\n");
}

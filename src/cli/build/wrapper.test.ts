/**
 * The generated entry's extension wiring: a project with none must be the exact bytes `crust build`
 * wrote before extensions existed, and one with files must import each, register them, and parse.
 */

import { describe, expect, test } from "bun:test";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { wrapperSource, type WrapperOptions } from "./wrapper.ts";

const transpiler = new Bun.Transpiler({ loader: "ts" });
const definePath = fileURLToPath(new URL("../../extensions/define.ts", import.meta.url));
const registryPath = fileURLToPath(new URL("../../extensions/registry.ts", import.meta.url));

const base: WrapperOptions = {
	configPath: "/p/crust.config.ts",
	entryPath: "/p/main.ts",
	assetsPath: "/p/dist/crust-assets.ts",
	runtimePath: "/crust/src/runtime.ts",
	extensionsPath: "/crust/src/extensions/registry.ts",
	projectDir: "/p",
};

describe("wrapperSource", () => {
	test("a project with no extensions is byte-identical to the entry from before", () => {
		const source = wrapperSource(base);
		const expected = [
			"// Generated by `crust build`. Edit nothing here.",
			`import config from ${JSON.stringify("/p/crust.config.ts")};`,
			`import { assets } from ${JSON.stringify("/p/dist/crust-assets.ts")};`,
			`import { startApp } from ${JSON.stringify("/crust/src/runtime.ts")};`,
			"// A built app has no dev server: drop dev.url so the window loads the",
			"// embedded document instead of a port nobody is listening on.",
			"const production = { ...config, dev: undefined };",
			"await startApp({",
			"\tconfig: production,",
			"\tassets,",
			`\tentryModule: () => import(${JSON.stringify("/p/main.ts")}),`,
			"});",
			"",
		].join("\n");

		expect(source).toBe(expected);
		expect(source).toBe(wrapperSource({ ...base, extensionFiles: [] }));
		expect(source).not.toContain("extension");
		expect(source).not.toContain("registry");
	});

	test("one extension loads lazily and registers at the registry line", () => {
		const source = wrapperSource({ ...base, extensionFiles: ["extensions/clock.ts"] });

		expect(source).toContain("async function extensionPlugins() {");
		expect(source).toContain(
			`\tconst extension0 = (await import(${JSON.stringify("/p/extensions/clock.ts")})).default;`,
		);
		expect(source).toContain(
			`import { extensionRegistry } from ${JSON.stringify("/crust/src/extensions/registry.ts")};`,
		);
		expect(source).toContain("const registry = extensionRegistry();");
		expect(source).toContain("registry.register(...(await extensionPlugins()));");
		expect(source).toContain("\tregistry,");
		// A static import would evaluate the extension on a crash-guard launch.
		expect(source).not.toContain("import extension0 from");
		expect(() => transpiler.transformSync(source)).not.toThrow();
	});

	test("two extensions load in the order the config listed them", () => {
		const files = ["extensions/clock.ts", "extensions/ping.ts"];
		const source = wrapperSource({ ...base, extensionFiles: files });
		const lines = source.split("\n");

		expect(lines.slice(0, 4)).toEqual([
			"// Generated by `crust build`. Edit nothing here.",
			"async function extensionPlugins() {",
			`\tconst extension0 = (await import(${JSON.stringify("/p/extensions/clock.ts")})).default;`,
			`\tconst extension1 = (await import(${JSON.stringify("/p/extensions/ping.ts")})).default;`,
		]);
		expect(source).toContain("registry.register(...(await extensionPlugins()));");

		const registerAt = lines.indexOf("registry.register(...(await extensionPlugins()));");
		const startAt = lines.indexOf("await startApp({");
		expect(registerAt).toBeGreaterThan(0);
		expect(registerAt).toBeLessThan(startAt);

		// The whole entry parses, so every generated line is real TypeScript.
		expect(() => transpiler.transformSync(source)).not.toThrow();
	});

	test("an absolute file is imported as given, not re-rooted", () => {
		const source = wrapperSource({ ...base, extensionFiles: ["/opt/shared/clock.ts"] });
		expect(source).toContain(
			`(await import(${JSON.stringify("/opt/shared/clock.ts")})).default;`,
		);
	});

	/**
	 * The bug this pins: the import block binds the module's default export, so a registry call
	 * naming `extension0.default` handed the registry `undefined` and a built app died with
	 * `register: not a plugin definition`. Running the generated entry is the only assertion that
	 * keeps the import shape and the register call from drifting apart again.
	 */
	test("the generated entry registers the real extension, not its .default", async () => {
		const dir = await mkdtemp(join(tmpdir(), "crust-wrapper-"));
		try {
			await mkdir(join(dir, "extensions"), { recursive: true });
			await writeFile(
				join(dir, "extensions", "clock.ts"),
				[
					`import { defineExtension } from ${JSON.stringify(definePath)};`,
					'export default defineExtension({ name: "clock", commands: { now: () => "12:00" } });',
					"",
				].join("\n"),
			);
			await writeFile(
				join(dir, "crust.config.ts"),
				"export default { app: {}, windows: [] };\n",
			);
			await writeFile(join(dir, "crust-assets.ts"), "export const assets = {};\n");
			await writeFile(
				join(dir, "runtime.ts"),
				[
					"export const seen: string[][] = [];",
					"export async function startApp(options: { registry?: { names(): string[] } }) {",
					"\tseen.push(options.registry?.names() ?? []);",
					"}",
					"",
				].join("\n"),
			);

			const entryPath = join(dir, "crust-entry.ts");
			await writeFile(
				entryPath,
				wrapperSource({
					configPath: join(dir, "crust.config.ts"),
					entryPath: join(dir, "main.ts"),
					assetsPath: join(dir, "crust-assets.ts"),
					runtimePath: join(dir, "runtime.ts"),
					extensionsPath: registryPath,
					projectDir: dir,
					extensionFiles: ["extensions/clock.ts"],
				}),
			);

			const runtime = (await import(pathToFileURL(join(dir, "runtime.ts")).href)) as {
				seen: string[][];
			};
			await import(pathToFileURL(entryPath).href);

			// A `.default` registration throws `register: not a plugin definition` instead.
			expect(runtime.seen).toEqual([["clock"]]);
		} finally {
			await rm(dir, { recursive: true, force: true });
		}
	});
});

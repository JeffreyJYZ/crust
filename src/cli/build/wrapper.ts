/**
 * The two generated entries: one for a project with a config, one for a single
 * file that has none.
 */

import { dirname, resolve } from "node:path";
import type { SingleApp } from "@/single";
import { extensionEntrySource, renderExtensionImports } from "@/extensions/entry-source.ts";

export interface WrapperOptions {
	configPath: string;
	entryPath: string;
	assetsPath: string;
	runtimePath: string;
	/** Project root a relative extension path resolves against. */
	projectDir: string;
	/** Module exporting `extensionRegistry`; read only when extensions exist. */
	extensionsPath: string;
	/** Extension files to embed; empty or absent is a project with none. */
	extensionFiles?: readonly string[];
}

/**
 * The generated entry a compiled crust app runs. `startApp` starts bridge and platform, and the wrapper's literal `import("<main.ts>")` runs the app; every path is an absolute literal, which is what lets `bun build --compile` bundle the config, the asset table, the runtime and each extension into one binary.
 * The crash guard is the only static import, and its marker check is the first statement: a guard launch is this same executable re-run with `CRUST_CRASH_GUARD` set, so anything imported above the check would be evaluated in a process whose whole job is to watch a pid and write a record. `startApp` reads the marker too, but only after the entry has been evaluated, which is why the check lives here. The app side is therefore `await import(...)`s, which `bun build --compile` bundles like any other (measured, `--trim` included).
 * `config.dev` is dropped from the generated entry and only there: `dev.url` names a dev server a built app does not have, and keeping it would point the window at a port nobody listens on. The project's own `crust.config.ts` is untouched, so `crust dev` still uses it.
 * Extensions are a function of dynamic imports plus a `registry.register(...)` right before `startApp`, which is the only place the registry exists; with no extension files both blocks vanish, so a project with none carries no trace of them.
 */
export function wrapperSource(options: WrapperOptions): string {
	const files = options.extensionFiles ?? [];
	const imports = extensionEntrySource({
		files,
		projectDir: options.projectDir,
		header: false,
	});
	const guardPath = resolve(dirname(options.runtimePath), "runtime-crash-guard.ts");

	const body = [
		"// Generated by `crust build`. Edit nothing here.",
		`import { runCrashGuardIfMarked } from ${JSON.stringify(guardPath)};`,
		"",
		"// A guard launch is this same executable re-run with a marker. It exits here, before any",
		"// app-side module is imported: the config, the asset table and the backend are all",
		"// module-level work, and a guard launch opens no window to spend it on.",
		"if (await runCrashGuardIfMarked()) process.exit(0);",
		"",
		`const config = (await import(${JSON.stringify(options.configPath)})).default;`,
		`const { assets } = await import(${JSON.stringify(options.assetsPath)});`,
		`const { startApp } = await import(${JSON.stringify(options.runtimePath)});`,
		...(files.length === 0
			? []
			: [
					`const { extensionRegistry } = await import(${JSON.stringify(options.extensionsPath)});`,
				]),
		"// A built app has no dev server: drop dev.url so the window loads the",
		"// embedded document instead of a port nobody is listening on.",
		"const production = { ...config, dev: undefined };",
		...(files.length === 0
			? []
			: [
					imports.trimEnd(),
					"const registry = extensionRegistry();",
					renderExtensionImports(files),
				]),
		"await startApp({",
		"\tconfig: production,",
		"\tassets,",
		// A built app serves only what it embedded. Without this, `startApp` derives a project
		// root from cwd and the bridge falls back to `<launch cwd>/public` for every path the
		// asset table lacks, so behaviour changes with the directory the binary was launched in.
		`\troot: ${JSON.stringify(NO_PROJECT_ROOT)},`,
		...(files.length === 0 ? [] : ["\tregistry,"]),
		`\tentryModule: () => import(${JSON.stringify(options.entryPath)}),`,
		"});",
	];
	return `${body.join("\n")}\n`;
}

/**
 * Never a directory, on any machine. A single-file build has no project tree on
 * the recipient's disk, so the bridge must answer every request from the
 * embedded table rather than from `cwd/public` — which is what `startApp`
 * would fall back to with no `root`.
 */
const NO_PROJECT_ROOT = "/crust-single/no-project";

/**
 * The generated entry a single-file `.app` runs. The config is a literal, not an import — no `crust.config.ts` exists and a build must not need one — and the page is already bundled JavaScript inside `crust-assets.ts`, so this carries only the backend and the framework's two commands.
 * The crash guard is the only static import, and the marker check runs before anything else is imported: a guard launch is this same executable re-run with `CRUST_CRASH_GUARD` set, so a static `import { app } from "src/index.ts"` would create the app singleton, register both commands and add the quit listener a second time, in a process whose whole job is to wait for a pid and write a record. `startApp` reads the marker too, but by then the module-level work has already happened, which is why the check belongs here. The app side is therefore four literal `await import(...)`s, which `bun build --compile` bundles like any other (measured, `--trim` included), so the binary still carries every one of them.
 */
export function singleWrapperSource(app: SingleApp, assetsPath: string, root: string): string {
	return [
		"// Generated by `crust build` from a single file. Edit nothing here.",
		`import { runCrashGuardIfMarked } from ${JSON.stringify(resolve(root, "src/runtime-crash-guard.ts"))};`,
		"",
		"// A guard launch is this same executable re-run with a marker. It exits here, before the",
		"// app below is imported: everything from `src/index.ts` to the quit listener is a",
		"// module-level side effect, and a guard launch opens no window to spend it on.",
		"if (await runCrashGuardIfMarked()) process.exit(0);",
		"",
		`const { app } = await import(${JSON.stringify(resolve(root, "src/index.ts"))});`,
		`const { assets } = await import(${JSON.stringify(assetsPath)});`,
		`const { startApp } = await import(${JSON.stringify(resolve(root, "src/runtime.ts"))});`,
		`const { registerSingleCommands } = await import(${JSON.stringify(resolve(root, "src/single.ts"))});`,
		"",
		`registerSingleCommands(app, ${JSON.stringify({ file: app.file, name: app.name })});`,
		'app.on("window-all-closed", () => { app.quit(); });',
		"await startApp({",
		`\tconfig: ${JSON.stringify(app.config, null, "\t")},`,
		"\tassets,",
		`\troot: ${JSON.stringify(NO_PROJECT_ROOT)},`,
		"\tentryModule: async () => {",
		"\t\tawait app.run();",
		"\t},",
		"});",
		"",
	].join("\n");
}

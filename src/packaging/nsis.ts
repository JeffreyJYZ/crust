/**
 * A Windows installer from `makensis`. The `.nsi` is generated and written before `makensis` is looked for, so a build machine without NSIS still yields a script a person can inspect or run elsewhere.
 * Nothing is downloaded: NSIS is a package-manager install, and a fetched compiler is not something this module should do behind a build step.
 */

import { mkdir, rm, stat, writeFile } from "node:fs/promises";
import { basename, join, resolve } from "node:path";
import { formatBytes } from "./build";
import { run } from "./exec";
import { findInstallerSidecars, sidecarFileLines, stageSidecars } from "./installers-sidecars";

/** The command runner, injectable so a test needs no tool installed. */
export type Exec = typeof run;

export interface NsisOptions {
	/** Directory holding the built Windows binary and the sidecars the build declared. */
	appPath: string;
	/** Installed executable filename, and the shortcut's target. */
	binaryName: string;
	/** Reverse-DNS identifier; names the script and the uninstall key. */
	id: string;
	/** Human name, the menu and uninstall-list entry. */
	name: string;
	/** Short version, e.g. `0.1.0`. */
	version: string;
	/** Publisher shown in the uninstall list. Defaults to the app name. */
	publisher?: string;
	/** Destination `.exe`. Defaults to `<appPath>/<id>-<version>-setup.exe`. */
	out?: string;
	/** Sidecar names from `build.sidecars`; when absent, read the built manifest instead. */
	sidecars?: readonly string[];
	exec?: Exec;
}

/** Everything the script needs, with paths already absolute. */
export interface NsisScriptOptions {
	appPath: string;
	binaryName: string;
	id: string;
	name: string;
	version: string;
	publisher?: string;
	/** Absolute path of the `.exe` the script writes. */
	out: string;
	/** Sidecar names the built app declared; each is installed at its own relative path. */
	sidecars?: readonly string[];
}

export interface NsisBuilt {
	ok: true;
	path: string;
	/** The generated script, kept so a caller can inspect it without makensis. */
	scriptPath: string;
	bytes: number;
	tool: string;
}

export interface NsisMissing {
	ok: false;
	reason: string;
	requires: string;
	scriptPath: string;
}

export type NsisResult = NsisBuilt | NsisMissing;

/**
 * The installer script. `RequestExecutionLevel user` means no elevation prompt, so the default directory has to be one that user can write: `$PROGRAMFILES64` needs an admin token and every non-elevated install would fail at `SetOutPath` — the default is `$LOCALAPPDATA\Programs`, the per-user location VS Code and Discord use. The same level means the HKLM write lands only when the installer is already elevated; HKCU is the key that always does, which is why both are written.
 */
export function nsisScript(options: NsisScriptOptions): string {
	const publisher = options.publisher ?? options.name;
	const sidecarFiles = sidecarFileLines(options.sidecars ?? [], options.appPath);
	const uninstall = `Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\\${APP_ID}`;
	return `; Generated by crust. Regenerate rather than edit.

!define APP_NAME "${options.name}"
!define APP_VERSION "${options.version}"
!define APP_ID "${options.id}"
!define PUBLISHER "${publisher}"
!define BINARY "${options.binaryName}"

Name "\${APP_NAME}"
OutFile "${options.out}"
InstallDir "$LOCALAPPDATA\\Programs\\${options.name}"
RequestExecutionLevel user

Page directory
Page instfiles

UninstPage uninstConfirm
UninstPage instfiles

Section "Install"
  SetOutPath "$INSTDIR"
  ; Install the binary and only the sidecars the build declared. Copying every file in dist
  ; shipped the macOS .app, stray AppImages and AppDirs, and earlier installers alongside it.
  File "${join(options.appPath, options.binaryName)}"
${sidecarFiles}  CreateShortcut "$SMPROGRAMS\\\${APP_NAME}.lnk" "$INSTDIR\\\${BINARY}"
  WriteUninstaller "$INSTDIR\\Uninstall.exe"
  WriteRegStr HKLM "${uninstall}" "DisplayName" "\${APP_NAME}"
  WriteRegStr HKLM "${uninstall}" "DisplayVersion" "\${APP_VERSION}"
  WriteRegStr HKLM "${uninstall}" "Publisher" "\${PUBLISHER}"
  WriteRegStr HKLM "${uninstall}" "UninstallString" "$INSTDIR\\Uninstall.exe"
  WriteRegStr HKCU "${uninstall}" "DisplayName" "\${APP_NAME}"
  WriteRegStr HKCU "${uninstall}" "DisplayVersion" "\${APP_VERSION}"
  WriteRegStr HKCU "${uninstall}" "Publisher" "\${PUBLISHER}"
  WriteRegStr HKCU "${uninstall}" "UninstallString" "$INSTDIR\\Uninstall.exe"
SectionEnd

Section "Uninstall"
  Delete "$INSTDIR\\Uninstall.exe"
  RMDir /r "$INSTDIR"
  Delete "$SMPROGRAMS\\\${APP_NAME}.lnk"
  DeleteRegKey HKLM "${uninstall}"
  DeleteRegKey HKCU "${uninstall}"
SectionEnd
`;
}

/** `which` is the POSIX lookup; Windows ships `where`, which prints one path per match — the first is the answer. */
async function toolOnPath(exec: Exec, tool: string): Promise<string | undefined> {
	const result = await exec([process.platform === "win32" ? "where" : "which", tool]);
	const found = result.stdout
		.split("\n")
		.map((line) => line.trim())
		.find((line) => line.length > 0);
	return result.code === 0 && found !== undefined ? found : undefined;
}

/**
 * Write the script and compile it. Throws when the app directory is absent — a caller mistake — and returns `ok: false` only for the one condition a person can fix by installing something.
 */
export async function buildNsis(options: NsisOptions): Promise<NsisResult> {
	const appStat = await stat(options.appPath).catch(() => undefined);
	if (!appStat?.isDirectory()) {
		throw new Error(
			`app directory ${options.appPath} does not exist; run the build step first`,
		);
	}

	// The install tree needs the declared sidecars and their manifest too: on macOS the
	// build put them inside the .app, while this builder packages the flat dist binary.
	const sidecars = await findInstallerSidecars(options.appPath);
	await stageSidecars(sidecars, options.appPath);

	// Beside the binary, inside `appPath`, like dmg and AppImage: a default in the
	// project root scatters one artefact away from every other release output.
	const outPath = resolve(
		options.out ?? join(options.appPath, `${options.id}-${options.version}-setup.exe`),
	);
	const scriptPath = join(resolve(outPath, ".."), `${options.id}.nsi`);
	await mkdir(resolve(scriptPath, ".."), { recursive: true });
	await writeFile(
		scriptPath,
		nsisScript({
			appPath: resolve(options.appPath),
			binaryName: options.binaryName,
			id: options.id,
			name: options.name,
			version: options.version,
			publisher: options.publisher,
			out: outPath,
			sidecars: options.sidecars ?? sidecars.names,
		}),
		"utf8",
	);

	const exec = options.exec ?? run;
	const tool = await toolOnPath(exec, "makensis");
	if (!tool) {
		return { ok: false, reason: "makensis is not on PATH", requires: "makensis", scriptPath };
	}

	// makensis overwrites by default, but a failed run leaves the previous exe
	// behind, and a stale one reads as a successful build.
	await rm(outPath, { force: true });
	const packed = await exec([tool, scriptPath]);
	if (packed.code !== 0) {
		const detail = (packed.stderr.trim() || packed.stdout.trim() || "no output")
			.split("\n")
			.join(" | ");
		throw new Error(`makensis failed (exit ${packed.code}): ${detail}`);
	}

	const bytes = (await stat(outPath)).size;
	return { ok: true, path: outPath, scriptPath, bytes, tool: basename(tool) };
}

/** One line a CLI can print without inventing a second size format. */
export function describeNsis(result: NsisResult): string {
	if (!result.ok) {
		return `nsis  script only  ${result.scriptPath}  (${result.reason}; install ${result.requires})`;
	}
	return `nsis ${formatBytes(result.bytes).padStart(9)}  ${result.bytes} bytes  ${result.path}  (script ${result.scriptPath})`;
}

/**
 * The generated entry fragment: `crust build` prepends these imports to the wrapper it writes, so
 * every extension travels inside the compiled binary instead of being read from a directory a
 * recipient does not have. Both functions index the same way — `extension0`, `extension1` — which
 * is the whole contract between the import block and the registry call.
 */

import { isAbsolute, resolve } from "node:path";

export interface ExtensionEntryOptions {
	/** Files to embed, absolute or relative to `projectDir`. Order is preserved. */
	files: readonly string[];
	projectDir: string;
	/** Defaults to true; a caller that already wrote the header passes false. */
	header?: boolean;
}

/** The imports to prepend; empty for a project with no extensions. */
export function extensionEntrySource(options: ExtensionEntryOptions): string {
	const { files, projectDir } = options;
	if (files.length === 0) return "";

	const lines: string[] = [];
	if (options.header !== false) lines.push("// Generated by `crust build`. Edit nothing here.");
	files.forEach((file, index) => {
		const path = isAbsolute(file) ? file : resolve(projectDir, file);
		lines.push(`import extension${index} from ${JSON.stringify(path)};`);
	});
	return `${lines.join("\n")}\n`;
}

/** The registry call that turns those imports into plugins; empty when there are none. */
export function renderExtensionImports(files: readonly string[]): string {
	if (files.length === 0) return "";
	// A default import already binds the module's default export, so `extension0`
	// is the plugin. `.default` on it was `undefined`, and the registry refused it.
	const plugins = files.map((_, index) => `extension${index}`);
	return `registry.register(${plugins.join(", ")});`;
}

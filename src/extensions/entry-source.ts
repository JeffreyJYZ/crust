/**
 * The generated entry fragment: `crust build` writes this block into the wrapper it generates, so
 * every extension travels inside the compiled binary instead of being read from a directory a
 * recipient does not have. The imports are dynamic and live inside a function, because a compiled
 * app re-runs its own executable as the crash guard: a static `import extension0 from "…"` would
 * evaluate the extension's module body on that launch, while a function body runs only at the
 * `registry.register` line, never while the entry itself is being evaluated.
 */

import { isAbsolute, resolve } from "node:path";

import { loadExtensions, type ExtensionError } from "./load.ts";

export interface ExtensionEntryOptions {
	/** Files to embed, absolute or relative to `projectDir`. Order is preserved. */
	files: readonly string[];
	projectDir: string;
	/** Defaults to true; a caller that already wrote the header passes false. */
	header?: boolean;
}

/** The plugin-loading function; empty for a project with no extensions. */
export function extensionEntrySource(options: ExtensionEntryOptions): string {
	const { files, projectDir } = options;
	if (files.length === 0) return "";

	const lines: string[] = [];
	if (options.header !== false) lines.push("// Generated by `crust build`. Edit nothing here.");
	lines.push("async function extensionPlugins() {");
	// Each import is guarded. `crust dev` reports a broken extension and keeps the window open,
	// and a build must not be the one place where the same file takes the whole app down before
	// `startApp` runs — an extension whose native dylib did not travel into the bundle is the
	// ordinary case, not a syntax error.
	lines.push("\tconst extensions = [];");
	files.forEach((file, index) => {
		const path = isAbsolute(file) ? file : resolve(projectDir, file);
		lines.push(`\ttry {`);
		lines.push(`\t\textensions.push((await import(${JSON.stringify(path)})).default);`);
		lines.push(`\t} catch (error${index}) {`);
		lines.push(
			`\t\tconsole.error("  extensions " + ${JSON.stringify(file)} + ": " + (error${index} instanceof Error ? error${index}.message : String(error${index})));`,
		);
		lines.push(`\t}`);
	});
	lines.push(`\treturn extensions;`);
	lines.push("}");
	return `${lines.join("\n")}\n`;
}

/** The registry call that awaits that function; empty when there are none. */
export function renderExtensionImports(files: readonly string[]): string {
	if (files.length === 0) return "";
	// A default import already binds the module's default export, so the awaited module's
	// `.default` is the plugin; the function returns exactly those, in config order.
	return "registry.register(...(await extensionPlugins()));";
}

export interface ExtensionValidation {
	/** Only the files that produced a valid, uniquely-named extension, in the order given. */
	files: string[];
	/** One entry per refused file, each naming the file and the reason. */
	errors: ExtensionError[];
}

/**
 * Build-time gate for the files `crust build` would embed. The generated entry pushes every module's
 * `.default` and the registry throws on `undefined` or a duplicate name, so a bad extension compiles
 * into an artefact that dies before `startApp`. The loader `crust dev` already applies here is the same
 * check: import each file, refuse a missing/invalid default and every claimant of a duplicate name.
 * A caller wires this into `build` by failing on `errors` and embedding only `files`; the registry
 * remains the second line at runtime.
 */
export async function validateExtensionEntries(
	files: readonly string[],
): Promise<ExtensionValidation> {
	const { loaded, errors } = await loadExtensions({ names: files });
	return { files: loaded, errors };
}

/** Lines a build can hand straight to `fail`, each naming the offending file and its reason. */
export function extensionErrorLines(errors: readonly ExtensionError[]): string[] {
	return errors.map((error) => `${error.file}: ${error.reason}`);
}

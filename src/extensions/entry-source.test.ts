import { describe, expect, test } from "bun:test";
import { join } from "node:path";

import { extensionEntrySource, renderExtensionImports } from "./entry-source.ts";

const projectDir = "/tmp/example-project";
const transpiler = new Bun.Transpiler({ loader: "ts" });

describe("extensionEntrySource", () => {
	test("emits one guarded dynamic import per file, inside a function, in the order given", () => {
		const source = extensionEntrySource({
			files: [join(projectDir, "extensions/clock.ts"), "extensions/ping.ts"],
			projectDir,
		});
		// A file that will not import is reported and skipped, never fatal: `crust dev` keeps running
		// through the same failure, and a build must not be the one place it takes the app down.
		expect(source).toContain("// Generated by `crust build`. Edit nothing here.");
		expect(source).toContain("async function extensionPlugins() {");
		expect(source).toContain(
			`await import(${JSON.stringify("/tmp/example-project/extensions/clock.ts")})`,
		);
		expect(source).toContain(
			`await import(${JSON.stringify("/tmp/example-project/extensions/ping.ts")})`,
		);
		expect(source.indexOf("clock.ts")).toBeLessThan(source.indexOf("ping.ts"));
		expect(source).toContain("} catch (error0) {");
		expect(source).toContain("} catch (error1) {");
		expect(source).toContain("return extensions;");
		// The whole block still compiles, which a broken template would not.
		expect(transpiler.transformSync(source)).toContain("await import");
	});

	test("is empty for a project with no extensions", () => {
		expect(extensionEntrySource({ files: [], projectDir })).toBe("");
	});

	test("never writes a static import, so declaring the block has no side effect", () => {
		const source = extensionEntrySource({ files: ["extensions/clock.ts"], projectDir });
		expect(source).not.toContain("import extension0 from");
		expect(source).toContain("await import(");
		expect(transpiler.transformSync(source)).toContain("await import");
	});
});

describe("renderExtensionImports", () => {
	test("awaits the function the import block declares", () => {
		expect(renderExtensionImports(["a.ts", "b.ts"])).toBe(
			"registry.register(...(await extensionPlugins()));",
		);
		expect(renderExtensionImports(["a.ts"])).toBe(
			"registry.register(...(await extensionPlugins()));",
		);
	});

	test("is empty when there is nothing to register", () => {
		expect(renderExtensionImports([])).toBe("");
	});

	test("the pair parses as one module", () => {
		const files = ["a.ts", "b.ts"];
		const module = [
			extensionEntrySource({ files, projectDir }),
			"const registry = { register: (..._plugins: unknown[]) => {} };",
			renderExtensionImports(files),
			"",
		].join("\n");
		expect(() => transpiler.transformSync(module)).not.toThrow();
	});
});
